const VISUALS: Record<VisualKind, ReturnType<typeof fixtureVisual>> = {
  diff: DIFF_VISUAL,
  expected: EXPECTED_VISUAL,
  observed: OBSERVED_VISUAL,
  recovered: EXPECTED_VISUAL,
};
const VISUAL_DIGESTS = Object.fromEntries(
  VISUAL_KINDS.map((kind) => [kind, VISUALS[kind].sha256]),
) as Record<VisualKind, string>;

function isVisualKind(value: string | undefined): value is VisualKind {
  return VISUAL_KINDS.some((kind) => kind === value);
}

type ApiState = "awaiting-approval" | "awaiting-closure" | "closed";

function run(state: ApiState, exposeApprovalNonce = false, approvalNonce = NONCE, reset = false) {
  const terminal = state === "closed";
  return demoRun(
    state,
    {
      lease_expires_at: terminal ? null : new Date(Date.now() + 15 * 60 * 1_000).toISOString(),
      ...(state === "awaiting-approval"
        ? { approval_nonce: exposeApprovalNonce ? approvalNonce : undefined }
        : {}),
      reset,
    },
    VISUAL_DIGESTS,
  );
}

function receipt() {
  return demoReceipt(VISUAL_DIGESTS);
}

type DemoApiOptions = {
  readonly ambiguousResetOnce?: boolean;
  readonly ambiguousStartOnce?: boolean;
  readonly initialState?: ApiState;
  readonly startConflict?: "demo-active-run-exists" | "demo-reset-required";
};

async function installDemoApi(page: Page, options: DemoApiOptions = {}) {
  let state: ApiState = options.initialState ?? "awaiting-approval";
  let resetComplete = false;
  let resetAttempts = 0;
  let startAttempts = 0;
  const mutations: unknown[] = [];
  const mutationBodies: string[] = [];
  await page.route("**/v1/demo/**", async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const visualKind = url.pathname.split("/").at(-1);
    if (
      request.method() === "GET" &&
      url.pathname.includes("/visuals/") &&
      isVisualKind(visualKind)
    ) {
      const visual = VISUALS[visualKind];
      await route.fulfill({
        body: visual.body,
        contentType: "image/png",
        headers: { "X-Content-SHA256": visual.sha256 },
      });
      return;
    }
    if (request.method() === "POST" && url.pathname === "/v1/demo/runs") {
      const body = request.postDataJSON() as Record<string, unknown>;
      mutations.push(body);
      mutationBodies.push(request.postData() ?? "");
      startAttempts += 1;
      if (options.startConflict !== undefined) {
        await route.fulfill({
          json: { code: options.startConflict, run_id: RUN_ID },
          status: 409,
        });
        return;
      }
      if (options.ambiguousStartOnce === true && startAttempts === 1) {
        await route.abort("connectionreset");
        return;
      }
      await route.fulfill({ json: run(state, true, String(body.approval_nonce)), status: 201 });
      return;
    }
    if (request.method() === "POST" && url.pathname.endsWith("/approve")) {
      mutations.push(request.postDataJSON());
      mutationBodies.push(request.postData() ?? "");
      state = "awaiting-closure";
      await route.fulfill({ json: run(state) });
      return;
    }
    if (request.method() === "POST" && url.pathname.endsWith("/close")) {
      mutations.push(request.postDataJSON());
      mutationBodies.push(request.postData() ?? "");
      state = "closed";
      await route.fulfill({ json: run(state) });
      return;
    }
    if (request.method() === "POST" && url.pathname.endsWith("/reset")) {
      mutations.push(request.postDataJSON());
      mutationBodies.push(request.postData() ?? "");
      resetAttempts += 1;
      resetComplete = true;
      if (options.ambiguousResetOnce === true && resetAttempts === 1) {
        await route.abort("connectionreset");
        return;
      }
      await route.fulfill({ json: demoReset() });
      return;
    }
    if (request.method() === "GET" && url.pathname.endsWith("/receipt")) {
      await route.fulfill({ json: receipt() });
      return;
    }
    if (request.method() === "GET" && url.pathname === `/v1/demo/runs/${RUN_ID}`) {
      await route.fulfill({ json: run(state, false, NONCE, resetComplete) });
      return;
    }
    await route.fulfill({ json: { code: "not-found" }, status: 404 });
  });
  return { mutationBodies, mutations };
}

