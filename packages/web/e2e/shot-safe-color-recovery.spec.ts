test("replays the persisted start request after response loss and reload", async ({ page }) => {
  const { mutationBodies, mutations } = await installDemoApi(page, {
    ambiguousStartOnce: true,
  });
  await page.goto("/");

  await page.getByRole("button", { name: "Investigate the color fault" }).click();
  await expect(page.getByRole("alert")).toContainText("service is unavailable");
  const pending = await page.evaluate(() => ({
    nonce: sessionStorage.getItem("colortrace.demo.approval-nonce"),
    startKey: sessionStorage.getItem("colortrace.demo.start-idempotency-key"),
  }));
  expect(pending.nonce).toBe(NONCE);
  expect(pending.startKey).toMatch(/^demo-start-/u);

  await page.reload();

  await expect(page.getByRole("heading", { name: "Expected versus observed" })).toBeVisible();
  expect(mutations.length).toBeGreaterThanOrEqual(2);
  expect(mutations.length).toBeLessThanOrEqual(3);
  expect(mutationBodies.every((body) => body === mutationBodies[0])).toBe(true);
  expect(
    mutations.every(
      (mutation) =>
        (mutation as { readonly idempotency_key?: unknown }).idempotency_key === pending.startKey,
    ),
  ).toBe(true);
  expect(
    await page.evaluate(() => ({
      run: sessionStorage.getItem("colortrace.demo.run-id"),
      startKey: sessionStorage.getItem("colortrace.demo.start-idempotency-key"),
    })),
  ).toEqual({ run: RUN_ID, startKey: null });
});

